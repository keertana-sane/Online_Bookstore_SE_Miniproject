
require('dotenv').config();
const mongoose = require('mongoose');
const bcrypt = require('bcryptjs');

const Book = require('../models/Book');
const User = require('../models/User');

const categories = [
  'Fiction',
  'Non-fiction',
  'Academic',
  'Fantasy',
  'Mystery',
  'Science',
  'Technology',
  'Biography',
  'History',
  'Romance'
];

const authors = [
  'Aarav Sharma',
  'Priya Rao',
  'Rohan Mehta',
  'Ananya Iyer',
  'Kabir Nair',
  'Meera Kapoor',
  'Arjun Reddy',
  'Ishita Das',
  'Dev Malhotra',
  'Neha Menon'
];

async function seedDatabase() {
  try {
    // Validate configuration BEFORE connecting to or modifying the database.
    const defaultPassword = process.env.SEED_DEFAULT_PASSWORD;

    if (!defaultPassword || defaultPassword.length < 12) {
      throw new Error(
        'Set SEED_DEFAULT_PASSWORD to a password of at least 12 characters in .env'
      );
    }

    if (!process.env.MONGO_URI) {
      throw new Error('MONGO_URI is missing from the .env file');
    }

    await mongoose.connect(process.env.MONGO_URI);
    console.log('Connected to MongoDB');

    // Remove only the sample records previously generated by this script.
    await Book.deleteMany({ seedBatch: 'BK-03' });

    await User.deleteMany({
      email: {
        $in: [
          'customer1@example.com',
          'customer2@example.com',
          'customer3@example.com',
          'admin@example.com'
        ]
      }
    });

    const books = Array.from({ length: 1000 }, (_, index) => ({
      title: `Sample Book ${String(index + 1).padStart(4, '0')}`,
      author: authors[index % authors.length],
      category: categories[index % categories.length],
      price: Number((199 + (index % 30) * 25.5).toFixed(2)),
      stock_quantity: index % 12 === 0 ? 0 : (index % 50) + 1,
      description: `Sample bookstore description for book ${index + 1}.`,
      cover_image: '',
      is_active: true,
      seedBatch: 'BK-03'
    }));

    await Book.insertMany(books);
    console.log('Inserted 1,000 sample books');

    const password_hash = await bcrypt.hash(defaultPassword, 12);

    const users = [
      {
        name: 'Customer One',
        email: 'customer1@example.com',
        password_hash,
        role: 'CUSTOMER',
        shipping_address: 'Bengaluru, Karnataka'
      },
      {
        name: 'Customer Two',
        email: 'customer2@example.com',
        password_hash,
        role: 'CUSTOMER',
        shipping_address: 'Mysuru, Karnataka'
      },
      {
        name: 'Customer Three',
        email: 'customer3@example.com',
        password_hash,
        role: 'CUSTOMER',
        shipping_address: 'Chennai, Tamil Nadu'
      },
      {
        name: 'Bookstore Admin',
        email: 'admin@example.com',
        password_hash,
        role: 'ADMIN_STAFF',
        shipping_address: ''
      }
    ];

    await User.insertMany(users);
    console.log('Inserted 3 customers and 1 admin');
    console.log('Seed completed successfully');
  } catch (error) {
    console.error('Seed failed:', error.message);
    process.exitCode = 1;
  } finally {
    if (mongoose.connection.readyState !== 0) {
      await mongoose.disconnect();
    }
  }
}

seedDatabase();
